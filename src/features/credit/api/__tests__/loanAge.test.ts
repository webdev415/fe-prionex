/**
 * «Днів з видачі» — ВЫЧИСЛЕНИЕ, а не поле модуля, и потому обязано быть
 * прижато тестом плотнее обычного: у ошибки здесь нет источника истины, с
 * которым оператор мог бы её сверить. Ошибись на день — и на карточке
 * появится срок, которого нет ни в одном ответе сервиса.
 */
import { describe, it, expect } from 'vitest'
import { loanAgeDays } from '../loanAge'

// Живая метка выдачи со стенда (FB-000074) — со смещением, как её шлёт модуль.
const DISBURSED = '2026-08-31T18:27:54.336420+00:00'

describe('loanAgeDays', () => {
  it('считает дни до среза сервиса, а не до «сегодня» браузера', () => {
    // Срез сервиса отстаёт на сутки от машины оператора — ровно тот случай,
    // ради которого точка отсчёта берётся из `as_of`: рядом на карточке лежит
    // просрочка, посчитанная на тот же день.
    const now = new Date('2026-09-05T10:00:00Z')
    expect(loanAgeDays(DISBURSED, '2026-09-04', now)).toBe(4)
    // Тот же кредит, тот же браузер, срез сегодняшний — на день больше.
    expect(loanAgeDays(DISBURSED, '2026-09-05', now)).toBe(5)
  })

  it('в день выдачи показывает ноль, а не единицу', () => {
    expect(loanAgeDays(DISBURSED, '2026-08-31', new Date('2026-08-31T20:00:00Z'))).toBe(0)
  })

  it('без среза считает от сегодняшней даты браузера', () => {
    // Дату берём КАЛЕНДАРНУЮ, локальную для оператора: 1 сентября в его
    // календаре — это первое сентября, в какой бы зоне он ни сидел.
    const now = new Date(2026, 8, 3, 9, 0, 0)
    expect(loanAgeDays(DISBURSED, undefined, now)).toBe(3)
    expect(loanAgeDays(DISBURSED, null, now)).toBe(3)
  })

  it('прижимает к нулю, а не показывает отрицательные дни', () => {
    // Часы сервера и браузера расходятся; «-1 день з видачі» на экране —
    // явный признак сломанной системы там, где сломаны только часы.
    expect(loanAgeDays(DISBURSED, '2026-08-30', new Date('2026-08-30T00:00:00Z'))).toBe(0)
  })

  it('не переводит метку в часовой пояс браузера', () => {
    // Иначе один и тот же кредит показывал бы разный возраст в Киеве и в
    // Калгари: метка выдачи 18:27 UTC в зоне UTC-6 попадает на тот же день,
    // а в UTC+13 — уже на следующий.
    const kyiv = loanAgeDays(DISBURSED, '2026-09-04', new Date('2026-09-04T00:30:00+03:00'))
    const calgary = loanAgeDays(DISBURSED, '2026-09-04', new Date('2026-09-03T17:30:00-06:00'))
    expect(kyiv).toBe(calgary)
  })

  it('возвращает null на метке, которую не разобрать', () => {
    expect(loanAgeDays(undefined, '2026-09-04', new Date())).toBeNull()
    expect(loanAgeDays('', '2026-09-04', new Date())).toBeNull()
    expect(loanAgeDays('31.08.2026', '2026-09-04', new Date())).toBeNull()
    // Конструктор Date молча откатил бы 13-й месяц на следующий год и выдал
    // уверенное число вместо «не знаем».
    expect(loanAgeDays('2026-13-45T00:00:00Z', '2026-09-04', new Date())).toBeNull()
    expect(loanAgeDays(DISBURSED, 'позавчора', new Date())).toBeNull()
  })
})
