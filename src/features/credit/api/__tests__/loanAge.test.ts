/**
 * Возраст кредита: тот же счёт, что видит клиент.
 *
 * Первая версия считала от `as_of` — среза сервиса. Довод был разумный
 * («иначе возраст и просрочка окажутся на разные даты»), а результат — нет:
 * `as_of` равен горизонту ночного расчёта и уходит вперёд. Замер на живом
 * стенде: кредиты, выданные 31.08, имели `as_of` 04.10, то есть оператор
 * увидел бы «34 днів з видачі» там, где клиент в кабинете видит «1 день».
 * Тридцать три дня расхождения на одном и том же кредите.
 *
 * Здесь закреплено правило кабинета
 * (`web-credit/apps/cabinet/src/components/loan-age.ts`): календарные дни до
 * СЕГОДНЯ В ЮРИСДИКЦИИ, будущая дата выдачи — не показывать.
 */
import { describe, it, expect } from 'vitest'
import { loanAgeDays, todayInTimezone } from '../loanAge'

const DISBURSED = '2026-08-31T18:27:54+00:00'

describe('loanAgeDays', () => {
  it('день выдачи — нулевой день, дальше по календарю', () => {
    expect(loanAgeDays(DISBURSED, '2026-08-31')).toBe(0)
    expect(loanAgeDays(DISBURSED, '2026-09-01')).toBe(1)
    expect(loanAgeDays(DISBURSED, '2026-09-04')).toBe(4)
  })

  it('час выдачи на счёт не влияет — сравниваются календарные дни', () => {
    // Кредит выдан почти в полночь UTC; для календаря это тот же день.
    expect(loanAgeDays('2026-08-31T23:59:00+00:00', '2026-09-01')).toBe(1)
    expect(loanAgeDays('2026-08-31T00:01:00+00:00', '2026-09-01')).toBe(1)
  })

  it('дата выдачи в будущем — null, а не ноль', () => {
    // Прижать к нулю значило бы выдать «0 днів» за измерение. Клиент в этом
    // случае строку прячет — прячем и мы.
    expect(loanAgeDays(DISBURSED, '2026-08-30')).toBeNull()
  })

  it('нечего или не из чего считать — null', () => {
    expect(loanAgeDays(undefined, '2026-09-04')).toBeNull()
    expect(loanAgeDays('', '2026-09-04')).toBeNull()
    expect(loanAgeDays(DISBURSED, null)).toBeNull()
    expect(loanAgeDays('31.08.2026', '2026-09-04')).toBeNull()
  })

  it('несуществующая дата — null, а не уверенная неправда', () => {
    // `new Date('2026-13-45')` молча откатывает на следующий год: разбирать
    // конструктором значило бы показать оператору посчитанное число вместо
    // признания, что метку не поняли.
    expect(loanAgeDays('2026-13-45T00:00:00Z', '2026-09-04')).toBeNull()
  })
})

describe('todayInTimezone', () => {
  it('берёт день юрисдикции, а не браузера', () => {
    // 01.09 в 00:30 по Киеву — это ещё 31.08 в Альберте (девять часов назад).
    // Без этого кредит у киевского оператора «старел» бы на день раньше, чем
    // у клиента, и оба были бы уверены в своей цифре.
    const kyivMidnight = new Date('2026-09-01T00:30:00+03:00')
    expect(todayInTimezone(kyivMidnight, 'America/Edmonton')).toBe('2026-08-31')
    expect(todayInTimezone(kyivMidnight, 'Europe/Kyiv')).toBe('2026-09-01')
  })

  it('отдаёт формат сервиса, чтобы обе стороны разбирались одинаково', () => {
    expect(todayInTimezone(new Date('2026-09-04T12:00:00Z'), 'America/Edmonton')).toMatch(
      /^\d{4}-\d{2}-\d{2}$/
    )
  })

  it('связка целиком: возраст у оператора совпадает с днём в Альберте', () => {
    // Тот самый случай со стенда: выдано 31.08, «сейчас» — 01.09 по Киеву.
    // Клиент видит 0 дней (в Альберте ещё 31-е) — и оператор обязан видеть 0.
    const now = new Date('2026-09-01T00:30:00+03:00')
    expect(loanAgeDays(DISBURSED, todayInTimezone(now, 'America/Edmonton'))).toBe(0)
  })
})
