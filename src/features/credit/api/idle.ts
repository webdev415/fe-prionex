/**
 * Сколько заявка стоит без движения.
 *
 * Модуль НЕ хранит время входа в каждый шаг анкеты: шаги внутри `in_progress`
 * статус не меняют, поэтому в журнале переходов (`audit`) их нет — там только
 * смены статуса. Единственная временная метка, которая уже приезжает, —
 * `updated_at`, время последнего изменения строки заявки.
 *
 * Она отвечает не на «когда клиент вошёл в шаг», а на «сколько нет движения».
 * Оператору этого хватает, чтобы увидеть, кого пора трогать: «застряв на
 * банківській перевірці, останній рух 3 години тому».
 *
 * Полную ленту этапов («вошёл в шаг 1 тогда-то, в шаг 2 тогда-то») здесь не
 * изобретаем: она требует новой записи в модуле и сквозной нумерации этапов,
 * единой для сайта, кабинета и CRM. Своя нумерация сейчас гарантированно
 * разъедется с чужой.
 */

/** Минуты без движения; `null` — если метку не разобрать. */
export function idleMinutes(updatedAt: string | undefined, now: Date): number | null {
  if (!updatedAt) return null
  // Модуль отдаёт метку со смещением (`+00:00`), но соседние источники CRM
  // присылают её и без зоны. Без явного `Z` такая строка читается как местное
  // время, и простой уезжает на часовой пояс браузера.
  let normalized = updatedAt.replace(' ', 'T')
  if (!normalized.endsWith('Z') && !/[-+]\d{2}:\d{2}$/.test(normalized)) normalized += 'Z'
  const then = new Date(normalized).getTime()
  if (Number.isNaN(then)) return null
  // Часы сервера и браузера расходятся; «минус пять минут простоя» — бессмыслица
  // на экране, поэтому прижимаем к нулю, а не показываем отрицательное.
  return Math.max(0, Math.floor((now.getTime() - then) / 60_000))
}

/**
 * Простой словами: «менше години» · «3 год» · «5 дн».
 *
 * Сокращения, а не полные слова, сознательно: украинский требует трёх форм
 * множественного числа («1 година», «3 години», «5 годин»), и словарь с
 * поддельными формами врал бы на каждом пятом значении. Сокращение «3 год»
 * верно при любом числе.
 *
 * `t` принимаем структурным типом, а не `TFunction`: функции нужен только
 * вызов с ключом и параметром, а дженерики i18next тянут за собой типы
 * словаря в чистый модуль.
 */
export function formatIdle(
  minutes: number,
  t: (key: string, options?: Record<string, unknown>) => string
): string {
  if (minutes < 60) return t('credit.idle.underHour')
  const hours = Math.floor(minutes / 60)
  if (hours < 24) return t('credit.idle.hoursShort', { value: hours })
  return t('credit.idle.daysShort', { value: Math.floor(hours / 24) })
}
