/**
 * Признак «кредитный блок в карточке клиента включён на этом стенде».
 *
 * Одно место чтения, потому что флаг читают трое: полоса вкладок, гейт данных
 * и фильтр списка «Позики». Три `import.meta.env` разошлись бы при первом же
 * переименовании, а разошедшийся флаг здесь означает «вкладки нет, но долг из
 * «Позики» уже убрали» — то есть долг пропал с экрана целиком.
 *
 * Сравнение со строкой `'true'`, а не `Boolean()`: сборщик подставляет
 * значение как строку, и `'false'` — истинная строка.
 *
 * Умолчание всех трёх шаблонов — `false`: блок едет раньше, чем у шлюза
 * появится группа `clients`, и до неё он показывал бы плашку «модуль
 * недоступний» каждому оператору.
 */
export const CREDIT_MODULE_FLAG = 'VITE_CREDIT_MODULE_ENABLED'

export function isCreditModuleEnabled(): boolean {
  return import.meta.env.VITE_CREDIT_MODULE_ENABLED === 'true'
}
