/**
 * Возраст кредита в днях — «скільки днів кредит живе».
 *
 * ⚠️ ПОЛЯ ТАКОГО В МОДУЛЕ НЕТ. Живой ответ стенда содержит ровно один счётчик
 * дней — `delinquency_days`; в контракте других `*_days` у кредита нет, есть
 * `term_days` продукта, то есть СРОК, а не прожитое. Значит это ВЫЧИСЛЕНИЕ, а
 * не факт сервиса.
 *
 * ⚠️ ЭТО ЗЕРКАЛО. Такой же счётчик уже показывается клиенту в его кабинете:
 * `web-credit/apps/cabinet/src/components/loan-age.ts` (+ `LoanCard.tsx`).
 * Правило взято ОТТУДА дословно, и вот почему это важнее, чем кажется.
 *
 * Первая версия этого файла считала от `as_of` — среза, на который сервис
 * посчитал остаток. Довод звучал разумно: «иначе возраст и просрочка окажутся
 * на разные даты». Но `as_of` в модуле равен `max(сегодня в юрисдикции,
 * materialized_as_of)`, то есть горизонту ночного расчёта, а он уходит ВПЕРЁД.
 * Замер на живом стенде: три кредита, выданные 31.08, имели `as_of` 04.10 —
 * оператор увидел бы «34 днів з видачі», а клиент в кабинете «1 день».
 * Тридцать три дня расхождения на том же самом кредите.
 *
 * Поэтому точка отсчёта — СЕГОДНЯ В ЮРИСДИКЦИИ, ровно как у клиента. Не «сегодня»
 * браузера: у оператора в Киеве день наступает на девять часов раньше, чем в
 * Альберте, и кредит «старел» бы на день раньше срока.
 *
 * Отрицательный возраст НЕ показываем (`null`), а не прижимаем к нулю — тоже
 * как у клиента: дата выдачи в будущем означает, что показывать нечего, а
 * «0 днів» на таком кредите выглядит как факт.
 *
 * Разойдётся с кабинетом — здесь ничто не покраснеет: общего пакета между
 * `fe-prionex` и `web-credit` нет. Это надпись, а не страж; настоящее решение —
 * поле от модуля (АР-16 архитектурного хребта: этап и производные считает
 * модуль, витрины рисуют).
 */
/**
 * Номер дня по календарю UTC из метки сервиса (`2026-08-31` и
 * `2026-08-31T18:27:54+00:00` дают один и тот же номер).
 *
 * Разбираем регулярным выражением, а не `new Date(...)`: конструктор
 * молча проглатывает `2026-13-45`, откатывая дату на следующий год, и вместо
 * «метку не разобрать» получилась бы уверенная неправда.
 */
function calendarDayNumber(value: string): number | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(value.trim())
  if (!match) return null
  const [year, month, day] = [Number(match[1]), Number(match[2]), Number(match[3])]
  const ms = Date.UTC(year, month - 1, day)
  const parsed = new Date(ms)
  // Проверка на переполнение: Date.UTC(2026, 12, 45) — валидное число, но это
  // уже не та дата, которую прислал сервис.
  if (
    parsed.getUTCFullYear() !== year ||
    parsed.getUTCMonth() !== month - 1 ||
    parsed.getUTCDate() !== day
  ) {
    return null
  }
  return Math.round(ms / 86_400_000)
}

/**
 * Дней с даты выдачи; `null` — метку не разобрать, выдачи не было или дата в
 * будущем.
 *
 * @param disbursedAt метка выдачи (`disbursed_at`)
 * @param today сегодняшняя дата В ЮРИСДИКЦИИ, `YYYY-MM-DD`. Считать её обязан
 *   вызывающий: только он знает юрисдикцию кредита.
 */
export function loanAgeDays(
  disbursedAt: string | null | undefined,
  today: string | null | undefined
): number | null {
  if (!disbursedAt || !today) return null
  const from = calendarDayNumber(disbursedAt)
  const to = calendarDayNumber(today)
  if (from === null || to === null) return null
  const days = to - from
  // Дата выдачи в будущем — показывать нечего. Клиент в этом случае строку
  // прячет; прижать к нулю значило бы выдать «0 днів» за измерение.
  return days >= 0 ? days : null
}

/** Сегодняшняя дата в часовом поясе юрисдикции, `YYYY-MM-DD`. */
export function todayInTimezone(now: Date, timeZone: string): string {
  // `en-CA` даёт ровно `YYYY-MM-DD` — тот же формат, в котором сервис присылает
  // календарные даты, поэтому обе стороны сравнения разбираются одинаково.
  return new Intl.DateTimeFormat('en-CA', {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now)
}
