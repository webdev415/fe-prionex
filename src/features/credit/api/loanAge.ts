/**
 * Возраст кредита в днях — «скільки днів кредит живе».
 *
 * ⚠️ ПОЛЯ ТАКОГО В МОДУЛЕ НЕТ. Живой ответ стенда (01.09.2026, `GET /loans`,
 * `GET /loans/{id}`, `GET /loans/{id}/state`) содержит ровно один счётчик дней
 * — `delinquency_days`; во всём контракте (`contracts/openapi.yaml` v0.1.19)
 * других `*_days` у кредита нет, есть только `term_days` продукта, то есть
 * СРОК, а не прожитое. Поэтому возраст считается здесь, из `disbursed_at`, и
 * это ВЫЧИСЛЕНИЕ, а не факт сервиса.
 *
 * Точка отсчёта — `as_of` из состояния кредита: тот самый день, на который
 * сервис посчитал просрочку и остаток. Считать от «сегодня» браузера нельзя:
 * карточка, открытая после полуночи, показала бы «31 день з видачі» рядом с
 * «20 днів прострочення», посчитанными на вчера, и оператор не смог бы
 * объяснить клиенту, откуда день разницы. Пока состояние не приехало,
 * отсчитываем от сегодняшней даты — ничего другого в этот момент нет.
 *
 * Обе даты берём КАЛЕНДАРНЫМИ, как их прислал сервис, и намеренно не
 * переводим в часовой пояс браузера: иначе один и тот же кредит показывал бы
 * разный возраст в Киеве и в Калгари. Цена — расхождение не больше суток на
 * займах, выданных ночью по времени юрисдикции.
 */

/**
 * Номер дня по календарю UTC из метки сервиса (`2026-08-31` и
 * `2026-08-31T18:27:54+00:00` дают один и тот же номер).
 *
 * Разбираем регулярным выражением, а не `new Date(...)`: конструктор
 * молча проглатывает `2026-13-45`, откатывая дату на следующий год, и вместо
 * «метку не разобрать» получилась бы уверенная неправда.
 */
function calendarDayNumber(value: string): number | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(value.trim())
  if (!match) return null
  const [year, month, day] = [Number(match[1]), Number(match[2]), Number(match[3])]
  const ms = Date.UTC(year, month - 1, day)
  const parsed = new Date(ms)
  // Проверка на переполнение: Date.UTC(2026, 12, 45) — валидное число, но это
  // уже не та дата, которую прислал сервис.
  if (
    parsed.getUTCFullYear() !== year ||
    parsed.getUTCMonth() !== month - 1 ||
    parsed.getUTCDate() !== day
  ) {
    return null
  }
  return Math.round(ms / 86_400_000)
}

/**
 * Дней с даты выдачи; `null` — если метку выдачи не разобрать.
 *
 * @param disbursedAt метка выдачи кредита (`disbursed_at`)
 * @param asOf срез сервиса (`as_of` из `/loans/{id}/state`); без него — `now`
 * @param now текущее время браузера; нужен собственный тик (`useNowTick`),
 *   иначе счётчик замрёт на моменте отрисовки карточки
 */
export function loanAgeDays(
  disbursedAt: string | null | undefined,
  asOf: string | null | undefined,
  now: Date
): number | null {
  if (!disbursedAt) return null
  const from = calendarDayNumber(disbursedAt)
  if (from === null) return null
  const to = asOf
    ? calendarDayNumber(asOf)
    : Math.round(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86_400_000)
  if (to === null) return null
  // Часы сервера и браузера расходятся, а `as_of` может отстать от выдачи на
  // свежем кредите. «-1 день з видачі» — бессмыслица на экране, поэтому
  // прижимаем к нулю: день выдачи и есть нулевой день.
  return Math.max(0, to - from)
}
