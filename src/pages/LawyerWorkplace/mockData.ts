// ─── Fallback detail builder ──────────────────────────────────────────────────

export function getLetterDetail(letterId: string): LetterDetail | null {
  if (MOCK_LETTER_DETAILS[letterId]) {
    return MOCK_LETTER_DETAILS[letterId]!
  }
  const summary = MOCK_LETTERS.find((l) => l.id === letterId)
  if (!summary) return null
  return {
    ...summary,
    recipientEmail: summary.mailbox,
    parameters: {
      letterType: summary.letterType ?? '',
      clientId: summary.clientId ?? '',
      clientLabel: summary.clientCode
        ? `${summary.clientCode} ${summary.clientName ?? ''}`.trim()
        : 'Not identified',
      contractId: '',
      contractLabel: '—',
      dueDate: '',
      dueDateHint: '',
      lawyerId: 'auto',
      lawyerLabel: 'Auto',
      autoConfidence: 0,
      confirmedCount: 0,
      totalParameters: 4,
    },
    replyDraft: '',
    thread: [
      {
        id: `${letterId}-msg-1`,
        direction: 'incoming',
        senderName: summary.senderName,
        senderEmail: summary.senderEmail,
        toMailbox: summary.mailbox,
        sentAt: summary.receivedAt,
        dateGroupLabel: 'Today',
        body: summary.subject,
      },
    ],
  }
}
