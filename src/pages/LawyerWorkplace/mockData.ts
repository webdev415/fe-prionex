// ─── Date helpers (all relative to NOW so tests always show correct labels) ───

function at(daysAgo: number, h: number, m = 0): string {
  const d = new Date()
  d.setDate(d.getDate() - daysAgo)
  d.setHours(h, m, 0, 0)
  return d.toISOString()
}

